package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// tree writes a source tree for one test: path relative to the source root -> content.
func tree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for rel, body := range files {
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// A FRAGMENT NOTHING INCLUDES REACHES NO SEAT. It still reads, to whoever opens src/fragments, as a
// duty some seat holds — and an edit to it changes nothing anywhere while every gate stays green.
func TestAFragmentNoSourceIncludesIsRefused(t *testing.T) {
	root := tree(t, map[string]string{
		"seat.md":                "---\nname: seat\n---\n@include fragments/held.md\n",
		"skills/shared/SKILL.md": "---\nname: shared\n---\n@include fragments/outer.md\n",
		"fragments/held.md":      "held\n",
		"fragments/outer.md":     "outer\n@include fragments/inner.md\n",
		"fragments/inner.md":     "inner\n",
		"fragments/orphan.md":    "orphan\n",
	})
	skills, err := skillNames(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(skills) != 1 || skills[0] != "shared" {
		t.Fatalf("skillNames = %v, want [shared]", skills)
	}
	dead, err := deadFragments(root, []string{"seat.md", skillSource("shared")})
	if err != nil {
		t.Fatal(err)
	}
	if len(dead) != 1 || dead[0] != filepath.Join("fragments", "orphan.md") {
		t.Errorf("deadFragments = %v, want only fragments/orphan.md — inner.md is reached through outer.md", dead)
	}
}

// AND THE GENERATOR REFUSES ONE ON THE SHIPPED TREE: sourceRoots is what main() takes its sources
// from, so the refusal runs wherever the generator does.
func TestTheGeneratorRefusesADeadFragmentInTheShippedTree(t *testing.T) {
	_, skills, err := sourceRoots("src")
	if err != nil {
		t.Fatal(err)
	}
	if len(skills) == 0 {
		t.Fatal("no skill source under src/skills — the generated skills have lost their sources")
	}
	// A copy of the tree with one fragment nothing includes.
	root := t.TempDir()
	if err := os.CopyFS(root, os.DirFS("src")); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "fragments", "orphan.md"), []byte("orphan\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, _, err := sourceRoots(root); err == nil || !strings.Contains(err.Error(), "orphan.md") {
		t.Errorf("sourceRoots = %v over a tree holding fragments/orphan.md, want a refusal naming it", err)
	}
}

func TestASkillSourceNamingAMissingFragmentIsRefused(t *testing.T) {
	root := tree(t, map[string]string{
		"skills/shared/SKILL.md": "---\nname: shared\n---\n\n@include fragments/gone.md\n",
	})
	if _, err := renderSkill(root, "shared"); err == nil || !strings.Contains(err.Error(), "fragments/gone.md") {
		t.Errorf("renderSkill = %v, want a refusal naming fragments/gone.md", err)
	}
	if _, err := deadFragments(root, []string{skillSource("shared")}); err == nil {
		t.Error("deadFragments walked a source naming a missing fragment and reported nothing")
	}
}

// THE GENERATED SKILL KEEPS ITS FRONTMATTER FIRST and names its source under it. The harness reads
// name and description from the block that opens the file.
func TestAGeneratedSkillNamesItsSourceUnderTheFrontmatter(t *testing.T) {
	root := tree(t, map[string]string{
		"skills/shared/SKILL.md": "---\nname: shared\ndescription: d\n---\n\n# shared\n\n@include fragments/duty.md\n\ntail\n",
		"fragments/duty.md":      "the duty\n",
	})
	got, err := renderSkill(root, "shared")
	if err != nil {
		t.Fatal(err)
	}
	want := "---\nname: shared\ndescription: d\n---\n\n" +
		"<!-- GENERATED by scripts/agentgen from scripts/agentgen/src/skills/shared/SKILL.md — DO NOT EDIT BY HAND. -->\n" +
		"\n# shared\n\nthe duty\n\ntail\n"
	if string(got) != want {
		t.Errorf("renderSkill wrote\n%q\nwant\n%q", got, want)
	}
	bare := tree(t, map[string]string{"skills/shared/SKILL.md": "# shared\n"})
	if _, err := renderSkill(bare, "shared"); err == nil {
		t.Error("a skill source with no frontmatter was rendered — the harness would load a skill with no description")
	}
}
