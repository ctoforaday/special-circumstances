// Command deadcode fails when any Go module in the repository holds a function nothing reaches.
//
// Dev tooling for this repository only. It runs golang.org/x/tools/cmd/deadcode — pinned as a
// tool dependency of this module, so CI and a developer's box analyse with the same version —
// over every module with `-test`, once per platform the modules ship on, and counts the findings.
//
// THE FAIL COUNT IS THE FINDING COUNT, AND THERE IS NO ALLOWLIST. deadcode itself exits 0 whatever
// it finds, so its exit status says only that the analysis ran; a function kept "for a reason"
// is kept by being called, and a list of excused names beside the gate would be the same
// hand-kept record the gate exists to replace.
//
// WHICH MODULES: every tracked go.mod outside a testdata directory. The go tool ignores testdata,
// so a module there is a test's fixture, not code anything builds; every other module is found,
// so a new one is covered the day it is added.
//
// WHAT IT TAKES AS REACHABLE: every `main` package under a module — the shipped binaries under
// cmd/ and the generators under devcmd/ alike — and, with `-test`, every test executable. So a
// function only a test calls is alive here; this gate answers "does anything at all reach it",
// not "does the product".
//
// GENERATED COPIES ARE JUDGED AS THEIR SOURCE. scripts/buildidgen and scripts/hookfailgen write
// one authored package into every plugin module, which cannot import it, and each copy carries a
// `// Code generated by … from <source>. DO NOT EDIT.` header. The source's own module calls
// little of it, and each copy's module calls only what that plugin needs, so neither list alone
// says whether the code is dead. A function in an authored source is therefore reported only
// when its own module and EVERY copy of the file leave it unreached. A source with no copy found
// stays judged by its own module alone, so a header that stops matching fails loudly instead of
// excusing anything. A finding in a generated file is otherwise not a failure: deadcode hides
// generated code by default, and the gate keeps that default for everything but this question.
//
// TWO PLATFORMS because the modules hold build-tagged files: a function reached only from a
// Windows file is dead on Linux's list and alive on Windows', and one platform's list alone
// would report it — or miss its opposite.
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/ctoforaday/special-circumstances/scripts/internal/gitx"
)

// platforms are the GOOS values every module is analysed under.
var platforms = []string{"linux", "windows"}

// finding is one function the tool reports unreachable. File is repository-relative, slash-separated.
type finding struct {
	File      string
	Line, Col int
	Name      string
	Generated bool
}

func (f finding) String() string {
	return fmt.Sprintf("%s:%d:%d: unreachable func: %s", f.File, f.Line, f.Col, f.Name)
}

func main() {
	root, err := gitx.Root()
	if err != nil {
		fmt.Fprintln(os.Stderr, "deadcode:", err)
		os.Exit(1)
	}
	tool, err := pinnedTool(filepath.Join(root, "scripts"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "deadcode:", err)
		os.Exit(1)
	}
	mods, err := modules(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "deadcode:", err)
		os.Exit(1)
	}
	copies, err := generatedCopies(root, mods)
	if err != nil {
		fmt.Fprintln(os.Stderr, "deadcode:", err)
		os.Exit(1)
	}
	found := 0
	for _, goos := range platforms {
		var all []finding
		for _, m := range mods {
			fs, err := unreachable(tool, root, m, goos)
			if err != nil {
				// NOT MEASURED IS NOT CLEAN: an analysis that could not load the module printed no
				// findings either.
				fmt.Fprintf(os.Stderr, "deadcode: %s GOOS=%s: the analysis did not run, so nothing was measured: %v\n", m, goos, err)
				os.Exit(1)
			}
			all = append(all, fs...)
		}
		for _, f := range dead(all, copies) {
			fmt.Printf("GOOS=%s %s\n", goos, f)
			found++
		}
	}
	if found > 0 {
		fmt.Fprintf(os.Stderr, "deadcode: %d unreachable function(s) — delete each, or call it; there is no allowlist\n", found)
		os.Exit(1)
	}
	fmt.Printf("deadcode: no unreachable function in %s (-test; GOOS %s)\n", strings.Join(mods, ", "), strings.Join(platforms, ", "))
}

// modules are the repository-relative directories of every tracked go.mod outside testdata.
func modules(root string) ([]string, error) {
	out, err := gitx.Run(root, "ls-files", "--", "go.mod", "*/go.mod")
	if err != nil {
		return nil, err
	}
	var mods []string
	for _, f := range gitx.Lines(out) {
		if inTestdata(f) {
			continue
		}
		mods = append(mods, path.Dir(f))
	}
	if len(mods) == 0 {
		return nil, fmt.Errorf("git lists no go.mod outside testdata, so there is nothing to analyse — that is not a clean tree")
	}
	sort.Strings(mods)
	return mods, nil
}

func inTestdata(p string) bool {
	for _, el := range strings.Split(path.Dir(p), "/") {
		if el == "testdata" {
			return true
		}
	}
	return false
}

// generatedHeader is the first line scripts/buildidgen and scripts/hookfailgen write into a copy.
var generatedHeader = regexp.MustCompile(`^// Code generated by \S+ from (\S+\.go)\. DO NOT EDIT\.$`)

// generatedCopies maps an authored source file to the copies generated from it, all
// repository-relative, found by the header each copy's first line carries.
func generatedCopies(root string, mods []string) (map[string][]string, error) {
	copies := map[string][]string{}
	for _, m := range mods {
		out, err := gitx.Run(filepath.Join(root, m), "ls-files", "--full-name", "--", "*.go")
		if err != nil {
			return nil, err
		}
		for _, f := range gitx.Lines(out) {
			first, err := firstLine(filepath.Join(root, filepath.FromSlash(f)))
			if err != nil {
				return nil, err
			}
			if m := generatedHeader.FindStringSubmatch(first); m != nil {
				copies[m[1]] = append(copies[m[1]], f)
			}
		}
	}
	return copies, nil
}

func firstLine(p string) (string, error) {
	fh, err := os.Open(p)
	if err != nil {
		return "", err
	}
	defer fh.Close()
	sc := bufio.NewScanner(fh)
	if sc.Scan() {
		return strings.TrimRight(sc.Text(), "\r"), nil
	}
	return "", sc.Err()
}

// dead is the failures among one platform's findings across every module: each hand-written
// function nothing reaches, except one in an authored source that some generated copy of its file
// still reaches. A finding in a generated file is evidence for its source, never a failure itself.
func dead(all []finding, copies map[string][]string) []finding {
	unreached := map[string]bool{}
	for _, f := range all {
		unreached[f.File+"\x00"+f.Name] = true
	}
	var out []finding
	for _, f := range all {
		if f.Generated {
			continue
		}
		reachedInACopy := false
		for _, c := range copies[f.File] {
			if !unreached[c+"\x00"+f.Name] {
				reachedInACopy = true
				break
			}
		}
		if !reachedInACopy {
			out = append(out, f)
		}
	}
	return out
}

// pinnedTool builds the deadcode this module pins and returns the executable's path.
func pinnedTool(scripts string) (string, error) {
	cmd := exec.Command("go", "tool", "-n", "deadcode")
	cmd.Dir = scripts
	var errOut bytes.Buffer
	cmd.Stderr = &errOut
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("resolving the pinned tool (`go tool -n deadcode` in scripts/): %v: %s", err, strings.TrimSpace(errOut.String()))
	}
	path := strings.TrimSpace(string(out))
	if path == "" {
		return "", fmt.Errorf("`go tool -n deadcode` named no executable")
	}
	return path, nil
}

// unreachable is the tool's findings for one module under one GOOS, generated files included,
// with every file named relative to root.
func unreachable(tool, root, module, goos string) ([]finding, error) {
	cmd := exec.Command(tool, "-test", "-generated", "-json", "./...")
	cmd.Dir = filepath.Join(root, filepath.FromSlash(module))
	// CGO off, as a cross-compile has it: the list is then the same whichever box computes it.
	cmd.Env = append(os.Environ(), "GOOS="+goos, "CGO_ENABLED=0")
	var out, errOut bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errOut
	if err := cmd.Run(); err != nil {
		return nil, fmt.Errorf("%v: %s", err, strings.TrimSpace(errOut.String()))
	}
	var pkgs []struct {
		Funcs []struct {
			Name     string
			Position struct {
				File      string
				Line, Col int
			}
			Generated bool
		}
	}
	if err := json.Unmarshal(out.Bytes(), &pkgs); err != nil {
		return nil, fmt.Errorf("reading the tool's -json output: %v", err)
	}
	var fs []finding
	for _, p := range pkgs {
		for _, f := range p.Funcs {
			// The tool names a file relative to the directory it ran in.
			file := f.Position.File
			if !filepath.IsAbs(file) {
				file = filepath.Join(cmd.Dir, file)
			}
			rel, err := filepath.Rel(root, file)
			if err != nil {
				return nil, err
			}
			fs = append(fs, finding{File: filepath.ToSlash(rel), Line: f.Position.Line, Col: f.Position.Col, Name: f.Name, Generated: f.Generated})
		}
	}
	return fs, nil
}
