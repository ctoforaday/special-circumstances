// write stages a one-package module for the tool to read.
func write(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, body := range files {
		p := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

const goMod = "module example.test/m\n\ngo 1.27\n"

// THE GATE SEES A DEAD FUNCTION, AND ONLY A DEAD ONE. A gate that lists nothing passes for ever,
// so the pinned tool is driven here over a module holding exactly one function nothing reaches,
// one a test alone reaches, and one only a second `main` package reaches.
func TestTheGateListsWhatNothingReachesAndNothingElse(t *testing.T) {
	tool, err := pinnedTool("..")
	if err != nil {
		t.Fatal(err)
	}
	dir := write(t, map[string]string{
		"go.mod":              goMod,
		"cmd/tool/main.go":    "package main\n\nimport \"example.test/m/lib\"\n\nfunc main() { lib.Live() }\n",
		"devcmd/gen/main.go":  "package main\n\nimport \"example.test/m/lib\"\n\nfunc main() { lib.OnlyTheGenerator() }\n",
		"lib/lib.go":          "package lib\n\nfunc Live() {}\n\nfunc OnlyTheGenerator() {}\n\nfunc OnlyATest() {}\n\nfunc dead() {}\n",
		"lib/lib_test.go":     "package lib\n\nimport \"testing\"\n\nfunc TestIt(t *testing.T) { OnlyATest() }\n",
		"lib/lib_windows.go":  "package lib\n\nfunc init() { onlyWindows() }\n",
		"lib/lib_platform.go": "package lib\n\nfunc onlyWindows() {}\n",
	})
	for goos, want := range map[string][]string{
		"linux":   {"dead", "onlyWindows"},
		"windows": {"dead"},
	} {
		fs, err := unreachable(tool, dir, ".", goos)
		if err != nil {
			t.Fatalf("GOOS=%s: %v", goos, err)
		}
		if lines := names(dead(fs, nil)); strings.Join(lines, ",") != strings.Join(want, ",") {
			t.Fatalf("GOOS=%s lists %v, want %v", goos, lines, want)
		}
		for _, f := range fs {
			if f.File != "lib/lib.go" && f.File != "lib/lib_platform.go" {
				t.Errorf("GOOS=%s names %q, want a path relative to the root it was given", goos, f.File)
			}
		}
	}
}

// A MODULE THE TOOL CANNOT LOAD IS NOT A CLEAN MODULE: the analysis prints no findings for it
// either, so the failure has to arrive as an error and never as an empty list.
func TestAModuleThatDoesNotLoadIsAnErrorNotAnEmptyList(t *testing.T) {
	tool, err := pinnedTool("..")
	if err != nil {
		t.Fatal(err)
	}
	dir := write(t, map[string]string{
		"go.mod":           goMod,
		"cmd/tool/main.go": "package main\n\nfunc main() { undefined() }\n",
	})
	if fs, err := unreachable(tool, dir, ".", "linux"); err == nil {
		t.Fatalf("a module that does not compile was read as %d finding(s) and no error", len(fs))
	}
	if fs, err := unreachable(tool, write(t, map[string]string{"go.mod": goMod, "lib/lib.go": "package lib\n\nfunc F() {}\n"}), ".", "linux"); err == nil {
		t.Fatalf("a module with no main package was read as %d finding(s) and no error — nothing roots the analysis", len(fs))
	}
}

func names(fs []finding) []string {
	var out []string
	for _, f := range fs {
		out = append(out, f.Name)
	}
	return out
}

// A GENERATED COPY'S CALL KEEPS ITS SOURCE ALIVE, AND ONLY THAT. The authored package a generator
// copies into modules that cannot import it is called from the copies, not from its own module;
// judged by its own module alone, every function the copies need reads as dead. A function no
// module and no copy reaches still fails, a finding inside the copy is never itself a failure, and
// a source whose copies the gate cannot find is judged by its own module — a header that stops
// matching reports more, never less.
func TestACopyReachingAFunctionKeepsItsSourceAliveAndNothingElse(t *testing.T) {
	tool, err := pinnedTool("..")
	if err != nil {
		t.Fatal(err)
	}
	lib := "package lib\n\nfunc Used() {}\n\nfunc OnlyTheCopyCalls() {}\n\nfunc NobodyCalls() {}\n"
	dir := write(t, map[string]string{
		"src/go.mod":          "module example.test/src\n\ngo 1.27\n",
		"src/cmd/t/main.go":   "package main\n\nimport \"example.test/src/lib\"\n\nfunc main() { lib.Used() }\n",
		"src/lib/lib.go":      lib,
		"copy/go.mod":         "module example.test/copy\n\ngo 1.27\n",
		"copy/cmd/t/main.go":  "package main\n\nimport \"example.test/copy/lib\"\n\nfunc main() { lib.OnlyTheCopyCalls() }\n",
		"copy/lib/lib.go":     "// Code generated by gen from src/lib/lib.go. DO NOT EDIT.\n\n" + lib,
		"testdata/m/go.mod":   goMod,
		"testdata/m/lib/x.go": "package lib\n",
	})
	for _, args := range [][]string{{"init", "-q"}, {"add", "."}} {
		cmd := exec.Command("git", args...)
		cmd.Dir = dir
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v: %s", args, err, out)
		}
	}
	mods, err := modules(dir)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Join(mods, ",") != "copy,src" {
		t.Fatalf("modules = %v, want copy and src and nothing under testdata", mods)
	}
	copies, err := generatedCopies(dir, mods)
	if err != nil {
		t.Fatal(err)
	}
	if got := copies["src/lib/lib.go"]; len(copies) != 1 || len(got) != 1 || got[0] != "copy/lib/lib.go" {
		t.Fatalf("copies = %v, want src/lib/lib.go copied once, to copy/lib/lib.go", copies)
	}
	var all []finding
	for _, m := range mods {
		fs, err := unreachable(tool, dir, m, "linux")
		if err != nil {
			t.Fatalf("%s: %v", m, err)
		}
		all = append(all, fs...)
	}
	if got := dead(all, copies); len(got) != 1 || got[0].File != "src/lib/lib.go" || got[0].Name != "NobodyCalls" {
		t.Errorf("dead = %v, want only src/lib/lib.go NobodyCalls", got)
	}
	if got := names(dead(all, nil)); strings.Join(got, ",") != "OnlyTheCopyCalls,NobodyCalls" {
		t.Errorf("with no copy found, dead = %v, want the source judged by its own module alone", got)
	}
}
