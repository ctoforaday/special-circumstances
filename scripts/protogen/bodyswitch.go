package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"

	gogen "google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/pluginpb"
)

// bodySwitchName is the file the body switch is written to, beside record.pb.go.
const bodySwitchName = "body_gen.go"

// bodySwitch renders recordpb.Body: a type switch over the wrapper types of Event's `body` oneof.
//
// The wrapper names come from the compiler/protogen package — the naming protoc-gen-go itself
// uses, from the same module version the version pin holds — so a case names exactly the type
// record.pb.go declares, conflict suffixes included, rather than a re-derivation of its rules.
//
// Body is on the read path of every guard and view: a write act calls it about 150k times. A
// descriptor lookup and a protoreflect Get per call cost about 500 ns; the switch costs a few.
func bodySwitch(req *pluginpb.CodeGeneratorRequest) ([]byte, error) {
	plugin, err := gogen.Options{}.New(req)
	if err != nil {
		return nil, fmt.Errorf("reading the compiled schema for the body switch: %w", err)
	}
	var event *gogen.Message
	for _, f := range plugin.Files {
		if !f.Generate {
			continue
		}
		for _, m := range f.Messages {
			if m.Desc.Name() == "Event" {
				event = m
			}
		}
	}
	if event == nil {
		return nil, fmt.Errorf("%s declares no Event message — there is no body to switch on", schemaRel)
	}
	var body *gogen.Oneof
	for _, o := range event.Oneofs {
		if o.Desc.Name() == "body" {
			body = o
		}
	}
	if body == nil || len(body.Fields) == 0 {
		return nil, fmt.Errorf("%s: Event has no `body` oneof, or one with no arms", schemaRel)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by scripts/protogen from %s. DO NOT EDIT.

package recordpb

import "google.golang.org/protobuf/proto"

// Body returns the event's body message, and whether it had one.
//
// A no-match returns false rather than a zero-valued message: an event with no body and an event
// whose body is empty are different facts, and the reader must be able to tell them apart.
//
// It is a type switch over the wrapper types of Event's `+"`body`"+` oneof, generated from the schema.
// TestBodyReadsBackEveryArmOfTheOneof walks the oneof through its descriptor, so an arm with no
// case here fails that test rather than reading as an event with no body.
func Body(ev *Event) (proto.Message, bool) {
	if ev == nil {
		return nil, false
	}
	switch b := ev.%s.(type) {
`, schemaRel, body.GoName)
	for _, f := range body.Fields {
		if f.Message == nil {
			return nil, fmt.Errorf("%s: the `body` arm %s is not a message — every arm of the oneof is an event body", schemaRel, f.Desc.Name())
		}
		fmt.Fprintf(&b, "\tcase *%s:\n\t\tif b != nil {\n\t\t\treturn b.%s, true\n\t\t}\n", f.GoIdent.GoName, f.GoName)
	}
	b.WriteString("\t}\n\treturn nil, false\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting the body switch: %w", err)
	}
	return src, nil
}

// verifyBodySwitch fails when the committed body switch differs from what the schema renders —
// stale after a schema change, or edited by hand.
func verifyBodySwitch(root string, want []byte) error {
	rel := filepath.Join(filepath.Dir(schemaRel), bodySwitchName)
	got, err := os.ReadFile(filepath.Join(root, rel))
	if err != nil {
		return fmt.Errorf("no body switch at %s: %w — run `go run ./protogen` and commit it", rel, err)
	}
	if !bytes.Equal(got, want) {
		return fmt.Errorf("%s differs from what %s renders. Run `go run ./protogen` and commit the "+
			"result; a switch missing an arm reads that arm's events as having no body", rel, schemaRel)
	}
	fmt.Printf("body switch is current (%s)\n", rel)
	return nil
}
