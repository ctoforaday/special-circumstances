// bodyDecodeRel is the file the body decode is written to: in recordsql, beside the read path that
// calls it, because it speaks SQL.
const bodyDecodeRel = "plugins/frank-exchange-of-views/tools/internal/record/recordsql/decode_gen.go"

// bodyDecode renders, for each body message, a reader of its table, list tables and oneof arm
// tables that scans each column straight into the typed Go field.
//
// THE SELECT LIST AND THE ASSIGNMENTS ARE ONE EMISSION. Column i of the statement and the Go field
// it lands in are written by the same loop iteration, so they cannot drift apart; a field added to
// the schema regenerates both.
//
// THE NAMES ARE THE SCHEMA'S, re-derived here. recordsql derives its tables from the descriptors at
// run time (schema.go: TableName, listTableNamed, armTable, oneofColumns), and this generator lives
// in another module, so it spells the same rules: a message's table is its name in snake_case, a
// list's table is its owner's table plus `_<field>`, an arm's table is its body's plus `_<arm>`, and
// a oneof with message arms carries `<oneof>_case`. A rule that drifts from schema.go names a table
// or column the record does not have, and every identifier here is table-qualified, so SQLite
// refuses the statement rather than reading an unknown double-quoted name as a string literal.
// recordsql's TestEveryBodyRoundTripsThroughTheGeneratedDecode writes every field of every body
// through the derived schema and reads it back through this code.
//
// Events reads every body of the record, about 1,900 on a fuzz-sized run, so a descriptor lookup and
// a protoreflect Set per field per body is a cost every reader pays; a typed assignment is not.
func bodyDecode(req *pluginpb.CodeGeneratorRequest) ([]byte, error) {
	body, err := eventBody(req)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by scripts/protogen from %s. DO NOT EDIT.

package recordsql

import (
	"database/sql"

	"github.com/ctoforaday/special-circumstances/plugins/frank-exchange-of-views/tools/internal/record/recordpb"
)

// bodyTables is one reader per arm of Event's `+"`body`"+` oneof, keyed by the arm's name — the
// event type's word.
var bodyTables = map[string]func() bodyTable{
`, schemaRel)
	for _, f := range body.Fields {
		if f.Message == nil {
			return nil, fmt.Errorf("%s: the `body` arm %s is not a message — every arm of the oneof is an event body", schemaRel, f.Desc.Name())
		}
		fmt.Fprintf(&b, "\t%q: func() bodyTable { return &%s{} },\n", f.Desc.Name(), readerName(f.Message))
	}
	b.WriteString("}\n")
	for _, f := range body.Fields {
		if err := decodeBodyMessage(&b, body.GoName, f); err != nil {
			return nil, err
		}
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting the body decode: %w\n%s", err, b.String())
	}
	return src, nil
}

// eventBody is Event's `body` oneof, as protoc-gen-go names it.
func eventBody(req *pluginpb.CodeGeneratorRequest) (*gogen.Oneof, error) {
	plugin, err := gogen.Options{}.New(req)
	if err != nil {
		return nil, fmt.Errorf("reading the compiled schema: %w", err)
	}
	var event *gogen.Message
	for _, f := range plugin.Files {
		if !f.Generate {
			continue
		}
		for _, m := range f.Messages {
			if m.Desc.Name() == "Event" {
				event = m
			}
		}
	}
	if event == nil {
		return nil, fmt.Errorf("%s declares no Event message — there is no body to switch on", schemaRel)
	}
	for _, o := range event.Oneofs {
		if o.Desc.Name() == "body" && len(o.Fields) > 0 {
			return o, nil
		}
	}
	return nil, fmt.Errorf("%s: Event has no `body` oneof, or one with no arms", schemaRel)
}

func readerName(m *gogen.Message) string { return lowerFirst(m.GoIdent.GoName) + "Table" }

func lowerFirst(s string) string { return strings.ToLower(s[:1]) + s[1:] }

// snake is recordsql's TableName rule: each capital becomes `_` and its lower case, except the first.
func snake(s string) string {
	var b strings.Builder
	for i, r := range s {
		if r >= 'A' && r <= 'Z' {
			if i > 0 {
				b.WriteByte('_')
			}
			b.WriteRune(r + 32)
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

// column is one scalar field's column: how it is scanned and how its value lands on the message.
type column struct {
	f       *gogen.Field
	scanVar string
}

// msgShape is one table's worth of a message: its scalar columns in field order, its lists, and its
// oneofs that have message arms.
type msgShape struct {
	table   string
	cols    []column
	lists   []*gogen.Field
	oneofs  []*gogen.Oneof            // non-synthetic oneofs with at least one message arm
	arms    map[string][]*gogen.Field // oneof name → its message arms
	scalars int                       // the columns a row must exist for: scalar fields, oneof scalar arms included
}

// shapeOf walks a message's fields as recordsql's schema does, refusing what the schema cannot store.
func shapeOf(m *gogen.Message, table string, isArm bool) (*msgShape, error) {
	s := &msgShape{table: table, arms: map[string][]*gogen.Field{}}
	for _, f := range m.Fields {
		where := fmt.Sprintf("%s (table %s)", f.Desc.FullName(), table)
		inRealOneof := f.Oneof != nil && !f.Oneof.Desc.IsSynthetic()
		switch {
		case f.Desc.IsMap():
			return nil, fmt.Errorf("%s is a map, which the record has no table shape for", where)
		case f.Desc.IsList():
			if f.Desc.Kind() == protoreflect.MessageKind || f.Desc.Kind() == protoreflect.GroupKind {
				return nil, fmt.Errorf("%s is a list of messages, which the record has no table shape for", where)
			}
			if _, err := scanType(f); err != nil {
				return nil, fmt.Errorf("%s: %w", where, err)
			}
			s.lists = append(s.lists, f)
		case f.Message != nil:
			if isArm || !inRealOneof {
				return nil, fmt.Errorf("%s is a message outside a body's oneof, which the record has no table shape for", where)
			}
			name := string(f.Oneof.Desc.Name())
			if len(s.arms[name]) == 0 {
				s.oneofs = append(s.oneofs, f.Oneof)
			}
			s.arms[name] = append(s.arms[name], f)
		default:
			if _, err := scanType(f); err != nil {
				return nil, fmt.Errorf("%s: %w", where, err)
			}
			s.cols = append(s.cols, column{f: f, scanVar: fmt.Sprintf("c%d", len(s.cols))})
			s.scalars++
		}
	}
	return s, nil
}

// scanType is the Go type a column of this field is scanned into: a Null type for a nullable
// scalar, the plain type for a list's NOT NULL value.
func scanType(f *gogen.Field) (string, error) {
	list := f.Desc.IsList()
	switch f.Desc.Kind() {
	case protoreflect.StringKind, protoreflect.EnumKind:
		if list {
			return "string", nil
		}
		return "sql.NullString", nil
	case protoreflect.BoolKind, protoreflect.Int32Kind, protoreflect.Int64Kind:
		if list {
			return "int64", nil
		}
		return "sql.NullInt64", nil
	case protoreflect.BytesKind:
		return "[]byte", nil
	}
	return "", fmt.Errorf("has no SQL type for kind %s", f.Desc.Kind())
}

// present is the condition under which a scanned column holds a value: NULL is absent, and absent
// is not zero.
func present(c column) string {
	if c.f.Desc.Kind() == protoreflect.BytesKind {
		return c.scanVar + " != nil"
	}
	return c.scanVar + ".Valid"
}

// valueExpr converts the scanned value v (of scanType's non-null form) to the field's Go type.
// An enum is resolved by the caller, through its word.
func valueExpr(f *gogen.Field, v string) string {
	switch f.Desc.Kind() {
	case protoreflect.BoolKind:
		return v + " != 0"
	case protoreflect.Int32Kind:
		return "int32(" + v + ")"
	}
	return v
}

// nonNull is the scanned column's value once present is known to hold.
func nonNull(c column) string {
	switch c.f.Desc.Kind() {
	case protoreflect.StringKind, protoreflect.EnumKind:
		return c.scanVar + ".String"
	case protoreflect.BoolKind, protoreflect.Int32Kind, protoreflect.Int64Kind:
		return c.scanVar + ".Int64"
	}
	return c.scanVar
}

// assign renders the statement that puts value expression v on message variable m: through the
// oneof's wrapper for a real oneof's scalar arm, through a pointer for a field with presence.
func assign(f *gogen.Field, m, v string) string {
	if f.Oneof != nil && !f.Oneof.Desc.IsSynthetic() {
		return fmt.Sprintf("%s.%s = &recordpb.%s{%s: %s}", m, f.Oneof.GoName, f.GoIdent.GoName, f.GoName, v)
	}
	if f.Desc.HasPresence() && f.Desc.Kind() != protoreflect.BytesKind {
		return fmt.Sprintf("%s.%s = ref(%s)", m, f.GoName, v)
	}
	return fmt.Sprintf("%s.%s = %s", m, f.GoName, v)
}

// emitRowRead writes the SELECT of one table's columns and the loop that builds a message per row
// into into[id], with value refusals recorded in bad.
func emitRowRead(b *bytes.Buffer, s *msgShape, goType, into, bad string, extra []string) {
	var sel []string
	sel = append(sel, `t."event_id"`)
	for _, c := range s.cols {
		sel = append(sel, fmt.Sprintf(`t.%q`, c.f.Desc.Name()))
	}
	for _, o := range s.oneofs {
		sel = append(sel, fmt.Sprintf(`t.%q`, string(o.Desc.Name())+"_case"))
	}
	fmt.Fprintf(b, "\t%s = map[int64]*recordpb.%s{}\n", into, goType)
	if len(sel) == 1 {
		// No column but the key: the row says nothing a missing row does not, so it is not read.
		return
	}
	// The scan targets are declared once per table and reused by every row: Scan overwrites each
	// one, NULL included, and a target declared per row is a heap allocation per column.
	b.WriteString("\t{\n\t\tvar id int64\n")
	targets := []string{"&id"}
	for _, c := range s.cols {
		st, _ := scanType(c.f)
		fmt.Fprintf(b, "\t\tvar %s %s\n", c.scanVar, st)
		targets = append(targets, "&"+c.scanVar)
	}
	for i := range s.oneofs {
		fmt.Fprintf(b, "\t\tvar k%d sql.NullString\n", i)
		targets = append(targets, fmt.Sprintf("&k%d", i))
	}
	fmt.Fprintf(b, "\t\tif err := scanRows(q, %q, `SELECT %s FROM %q t`, []any{%s}, func() {\n",
		s.table, strings.Join(sel, ", "), s.table, strings.Join(targets, ", "))
	fmt.Fprintf(b, "\t\tm := &recordpb.%s{}\n", goType)
	for _, c := range s.cols {
		fmt.Fprintf(b, "\t\tif %s {\n", present(c))
		if c.f.Desc.Kind() == protoreflect.EnumKind {
			fmt.Fprintf(b, "\t\t\tif v, err := wordOf[recordpb.%s](%q, %s); err != nil {\n\t\t\t\t%s = refuse(%s, id, err)\n\t\t\t} else {\n\t\t\t\t%s\n\t\t\t}\n",
				c.f.Enum.GoIdent.GoName, s.table+"."+string(c.f.Desc.Name()), nonNull(c), bad, bad, assign(c.f, "m", "v"))
		} else {
			fmt.Fprintf(b, "\t\t\t%s\n", assign(c.f, "m", valueExpr(c.f, nonNull(c))))
		}
		b.WriteString("\t\t}\n")
	}
	for i := range s.oneofs {
		fmt.Fprintf(b, "\t\tif k%d.Valid && k%d.String != \"\" {\n\t\t\tif %s == nil {\n\t\t\t\t%s = map[int64]string{}\n\t\t\t}\n\t\t\t%s[id] = k%d.String\n\t\t}\n",
			i, i, extra[i], extra[i], extra[i], i)
	}
	fmt.Fprintf(b, "\t\t%s[id] = m\n\t\t}); err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n", into)
}

// emitListReads writes one ordered scan per list table, appending to the owner's message.
func emitListReads(b *bytes.Buffer, s *msgShape, goType, into, bad string) {
	for _, f := range s.lists {
		table := s.table + "_" + string(f.Desc.Name())
		st, _ := scanType(f)
		fmt.Fprintf(b, "\tif err := scanList(q, %q, `SELECT l.\"event_id\", l.\"value\" FROM %q l ORDER BY l.\"event_id\", l.\"ord\"`, func(id int64, v %s) {\n",
			table, table, st)
		fmt.Fprintf(b, "\t\tm := %s[id]\n\t\tif m == nil {\n", into)
		if s.scalars > 0 {
			b.WriteString("\t\t\treturn // the owner's row is missing, and its event is refused for that\n")
		} else {
			fmt.Fprintf(b, "\t\t\tm = &recordpb.%s{}\n\t\t\t%s[id] = m\n", goType, into)
		}
		b.WriteString("\t\t}\n")
		if f.Desc.Kind() == protoreflect.EnumKind {
			fmt.Fprintf(b, "\t\tw, err := wordOf[recordpb.%s](%q, v)\n\t\tif err != nil {\n\t\t\t%s = refuse(%s, id, err)\n\t\t\treturn\n\t\t}\n",
				f.Enum.GoIdent.GoName, table, bad, bad)
			fmt.Fprintf(b, "\t\tm.%s = append(m.%s, w)\n", f.GoName, f.GoName)
		} else {
			fmt.Fprintf(b, "\t\tm.%s = append(m.%s, %s)\n", f.GoName, f.GoName, valueExpr(f, "v"))
		}
		b.WriteString("\t}); err != nil {\n\t\treturn err\n\t}\n")
	}
}

// decodeBodyMessage writes one body's reader: its struct, load and attach.
func decodeBodyMessage(b *bytes.Buffer, oneof string, arm *gogen.Field) error {
	m := arm.Message
	table := snake(string(m.Desc.Name()))
	s, err := shapeOf(m, table, false)
	if err != nil {
		return err
	}
	goType := m.GoIdent.GoName
	name := readerName(m)

	type armShape struct {
		f        *gogen.Field
		s        *msgShape
		rows     string
		bad      string
		caseWord string
	}
	var caseFields []string
	armsOf := map[string][]armShape{}
	for _, o := range s.oneofs {
		caseFields = append(caseFields, "t."+lowerFirst(o.GoName)+"Case")
		for _, af := range s.arms[string(o.Desc.Name())] {
			atable := table + "_" + string(af.Desc.Name())
			as, err := shapeOf(af.Message, atable, true)
			if err != nil {
				return err
			}
			base := lowerFirst(o.GoName) + af.GoName
			armsOf[string(o.Desc.Name())] = append(armsOf[string(o.Desc.Name())],
				armShape{f: af, s: as, rows: "t." + base, bad: "t." + base + "Bad", caseWord: string(af.Desc.Name())})
		}
	}

	fmt.Fprintf(b, "\n// %s reads the %q table whole, with its lists and oneof arms, keyed by event.\ntype %s struct {\n", name, table, name)
	fmt.Fprintf(b, "\trows map[int64]*recordpb.%s\n\tbad  map[int64]error\n", goType)
	for _, o := range s.oneofs {
		fmt.Fprintf(b, "\t%sCase map[int64]string\n", lowerFirst(o.GoName))
		for _, a := range armsOf[string(o.Desc.Name())] {
			fmt.Fprintf(b, "\t%s map[int64]*recordpb.%s\n\t%s map[int64]error\n",
				strings.TrimPrefix(a.rows, "t."), a.f.Message.GoIdent.GoName, strings.TrimPrefix(a.bad, "t."))
		}
	}
	b.WriteString("}\n")

	fmt.Fprintf(b, "\nfunc (t *%s) load(q Querier) error {\n", name)
	emitRowRead(b, s, goType, "t.rows", "t.bad", caseFields)
	emitListReads(b, s, goType, "t.rows", "t.bad")
	for oi, o := range s.oneofs {
		for _, a := range armsOf[string(o.Desc.Name())] {
			fmt.Fprintf(b, "\t// Only an arm some row names is read.\n\tif caseNamed(%s, %q) {\n", caseFields[oi], a.caseWord)
			ag := a.f.Message.GoIdent.GoName
			emitRowRead(b, a.s, ag, a.rows, a.bad, nil)
			emitListReads(b, a.s, ag, a.rows, a.bad)
			b.WriteString("\t}\n")
		}
	}
	b.WriteString("\treturn nil\n}\n")

	fmt.Fprintf(b, "\nfunc (t *%s) attach(ev *recordpb.Event, id int64) error {\n\tm := t.rows[id]\n\tif m == nil {\n", name)
	if s.scalars > 0 {
		fmt.Fprintf(b, "\t\treturn noBody(id, %q)\n", table)
	} else {
		fmt.Fprintf(b, "\t\tm = &recordpb.%s{}\n", goType)
	}
	b.WriteString("\t}\n\tif err := t.bad[id]; err != nil {\n\t\treturn err\n\t}\n")
	for oi, o := range s.oneofs {
		fmt.Fprintf(b, "\tswitch %s[id] {\n", caseFields[oi])
		for _, a := range armsOf[string(o.Desc.Name())] {
			fmt.Fprintf(b, "\tcase %q:\n\t\ta := %s[id]\n\t\tif a == nil {\n", a.caseWord, a.rows)
			if a.s.scalars > 0 {
				fmt.Fprintf(b, "\t\t\treturn noBody(id, %q)\n", a.s.table)
			} else {
				fmt.Fprintf(b, "\t\t\ta = &recordpb.%s{}\n", a.f.Message.GoIdent.GoName)
			}
			fmt.Fprintf(b, "\t\t}\n\t\tif err := %s[id]; err != nil {\n\t\t\treturn err\n\t\t}\n", a.bad)
			fmt.Fprintf(b, "\t\tm.%s = &recordpb.%s{%s: a}\n", o.GoName, a.f.GoIdent.GoName, a.f.GoName)
		}
		b.WriteString("\t}\n")
	}
	fmt.Fprintf(b, "\tev.%s = &recordpb.%s{%s: m}\n\treturn nil\n}\n", oneof, arm.GoIdent.GoName, arm.GoName)
	return nil
}
