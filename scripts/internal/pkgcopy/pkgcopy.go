// Package pkgcopy writes one authored package into every plugin module that needs it, and checks
// that the copies have not drifted. It is the body of buildidgen, hookfailgen and gcpolicygen: each
// names its source and its targets and hands over.
//
// Each plugin's tools/ has to build on its own — `sc-doctor --fix` builds from the installed plugin
// root, and a consumer with one plugin installed has only that plugin's tree — so a shared module is
// not available and the code is copied. The copies are generated because hand-kept ones drift.
package pkgcopy

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/ctoforaday/special-circumstances/scripts/internal/gitx"
)

// Main runs a generator named tool that copies srcDir (repository-relative) into each target
// directory. With -check it writes nothing and fails when a copy is missing or has drifted. It
// returns the process exit code.
func Main(tool, srcDir string, targets []string) int {
	check := flag.Bool("check", false, "verify every copy matches the authored source instead of writing them")
	flag.Parse()

	root, err := gitx.Root()
	if err != nil {
		fmt.Fprintln(os.Stderr, tool+":", err)
		return 1
	}
	want, err := render(root, tool, srcDir)
	if err != nil {
		fmt.Fprintln(os.Stderr, tool+":", err)
		return 1
	}

	var stale []string
	for _, t := range targets {
		for name, body := range want {
			path := filepath.Join(root, t, name)
			if !*check {
				if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
					fmt.Fprintln(os.Stderr, tool+":", err)
					return 1
				}
				if err := os.WriteFile(path, body, 0o644); err != nil {
					fmt.Fprintln(os.Stderr, tool+":", err)
					return 1
				}
				continue
			}
			got, err := os.ReadFile(path)
			if err != nil {
				stale = append(stale, fmt.Sprintf("%s/%s is missing (%v)", t, name, err))
				continue
			}
			if !bytes.Equal(got, body) {
				stale = append(stale, fmt.Sprintf("%s/%s has drifted from %s/%s", t, name, srcDir, name))
			}
		}
	}

	if !*check {
		fmt.Printf("%s: wrote %d file(s) into %d module(s)\n", tool, len(want), len(targets))
		return 0
	}
	if len(stale) > 0 {
		for _, s := range stale {
			fmt.Fprintln(os.Stderr, tool+":", s)
		}
		fmt.Fprintf(os.Stderr, "%s: edit %s and run `(cd scripts && go run ./%s)` — "+
			"the copies are generated so the rule they carry is stated once.\n", tool, srcDir, tool)
		return 1
	}
	fmt.Printf("%s: %d module(s) match %s\n", tool, len(targets), srcDir)
	return 0
}

// render reads the authored package and returns each file's generated form.
func render(root, tool, srcDir string) (map[string][]byte, error) {
	entries, err := os.ReadDir(filepath.Join(root, srcDir))
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		body, err := os.ReadFile(filepath.Join(root, srcDir, name))
		if err != nil {
			return nil, err
		}
		var b bytes.Buffer
		fmt.Fprintf(&b, "// Code generated by scripts/%s from %s/%s. DO NOT EDIT.\n\n", tool, srcDir, name)
		b.Write(body)
		out[name] = b.Bytes()
	}
	// An authored package that reads as EMPTY would generate nothing and report success,
	// leaving whatever is already in the modules untouched and unchecked.
	if len(out) == 0 {
		return nil, fmt.Errorf("%s holds no non-test .go files — refusing to generate nothing", srcDir)
	}
	return out, nil
}
