// Command secretsgen writes the secrets gate's gitleaks configuration as Go: the table in
// internal/secrets/table.go is gitleaks.toml as gitleaks translates it — extended with
// gitleaks' default configuration — with every pattern held as its source text. The gate then
// builds its detector from the table, compiling only the rules a payload's keywords select,
// and parses no TOML.
//
//	go run ./devcmd/secretsgen          rewrite internal/secrets/table.go
//	go run ./devcmd/secretsgen -check   exit 1 when the committed table is stale
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"

	"github.com/zricethezav/gitleaks/v8/config"

	"github.com/ctoforaday/special-circumstances/plugins/prosthetic-conscience/tools/internal/secrets"
	"github.com/ctoforaday/special-circumstances/plugins/prosthetic-conscience/tools/internal/secrets/gitleakstoml"
)

// out is the table's path relative to the tools module.
const out = "internal/secrets/table.go"

func main() {
	check := flag.Bool("check", false, "exit 1 when "+out+" is stale instead of rewriting it")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "secretsgen:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	cfg, err := gitleakstoml.Config()
	if err != nil {
		return err
	}
	src, err := render(secrets.SpecOf(cfg))
	if err != nil {
		return err
	}
	if !check {
		return os.WriteFile(out, src, 0o644)
	}
	have, err := os.ReadFile(out)
	if err != nil {
		return err
	}
	if !bytes.Equal(have, src) {
		return fmt.Errorf("%s is stale against %s and gitleaks' default configuration: run `go run ./devcmd/secretsgen`", out, gitleakstoml.File)
	}
	return nil
}

// render writes s as the Go source of table.go.
func render(s secrets.Spec) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by devcmd/secretsgen from " + gitleakstoml.File + " and gitleaks' default\n")
	b.WriteString("// configuration. DO NOT EDIT.\n\npackage secrets\n\n")
	b.WriteString("import \"github.com/zricethezav/gitleaks/v8/config\"\n\n")
	b.WriteString("var table = Spec{\n")
	field(&b, "Title", q(s.Title))
	field(&b, "Description", q(s.Description))
	field(&b, "Extend", fmt.Sprintf("config.Extend{Path: %s, URL: %s, UseDefault: %t, DisabledRules: %s}",
		q(s.Extend.Path), q(s.Extend.URL), s.Extend.UseDefault, strs(s.Extend.DisabledRules)))
	field(&b, "Path", q(s.Path))
	field(&b, "MinVersion", q(s.MinVersion))
	field(&b, "Keywords", strs(s.Keywords))
	field(&b, "OrderedRules", strs(s.OrderedRules))
	field(&b, "Allowlists", allows(s.Allowlists))
	b.WriteString("Rules: []RuleSpec{\n")
	for _, r := range s.Rules {
		b.WriteString("{\n")
		field(&b, "ID", q(r.ID))
		field(&b, "Description", q(r.Description))
		field(&b, "Regex", q(r.Regex))
		field(&b, "Path", q(r.Path))
		field(&b, "SecretGroup", strconv.Itoa(r.SecretGroup))
		field(&b, "Entropy", strconv.FormatFloat(r.Entropy, 'g', -1, 64))
		field(&b, "Keywords", strs(r.Keywords))
		field(&b, "Tags", strs(r.Tags))
		field(&b, "Allowlists", allows(r.Allowlists))
		if r.Required != nil {
			var rq []string
			for _, x := range r.Required {
				rq = append(rq, fmt.Sprintf("{RuleID: %s, WithinLines: %s, WithinColumns: %s}", q(x.RuleID), intp(x.WithinLines), intp(x.WithinColumns)))
			}
			field(&b, "Required", "[]RequiredSpec{"+strings.Join(rq, ", ")+"}")
		}
		field(&b, "SkipReport", strconv.FormatBool(r.SkipReport))
		b.WriteString("},\n")
	}
	b.WriteString("},\n}\n")
	return format.Source([]byte(b.String()))
}

func field(b *strings.Builder, name, value string) {
	b.WriteString(name + ": " + value + ",\n")
}

func q(s string) string { return strconv.Quote(s) }

// strs keeps nil and empty apart: gitleaks gives a rule without keywords an empty slice, and
// the table equals the translation only if it does too.
func strs(xs []string) string {
	if xs == nil {
		return "nil"
	}
	var qs []string
	for _, x := range xs {
		qs = append(qs, q(x))
	}
	return "[]string{" + strings.Join(qs, ", ") + "}"
}

func intp(p *int) string {
	if p == nil {
		return "nil"
	}
	return fmt.Sprintf("new(%d)", *p)
}

func allows(as []secrets.AllowSpec) string {
	if as == nil {
		return "nil"
	}
	var b strings.Builder
	b.WriteString("[]AllowSpec{\n")
	for _, a := range as {
		var cond string
		switch a.MatchCondition {
		case config.AllowlistMatchOr:
			cond = "config.AllowlistMatchOr"
		case config.AllowlistMatchAnd:
			cond = "config.AllowlistMatchAnd"
		default:
			panic(fmt.Sprintf("allowlist %q: a match condition this generator does not write: %d", a.Description, a.MatchCondition))
		}
		fmt.Fprintf(&b, "{Description: %s, MatchCondition: %s, Commits: %s, Paths: %s, RegexTarget: %s, Regexes: %s, StopWords: %s},\n",
			q(a.Description), cond, strs(a.Commits), strs(a.Paths), q(a.RegexTarget), strs(a.Regexes), strs(a.StopWords))
	}
	b.WriteString("}")
	return b.String()
}
