package planguard_test

import (
	"context"
	"crypto/sha256"
	"database/sql"
	"encoding/hex"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"github.com/ctoforaday/special-circumstances/plugins/frank-exchange-of-views/tools/internal/goldentest"
	"github.com/ctoforaday/special-circumstances/plugins/frank-exchange-of-views/tools/internal/record/planguard"
)

// shapesBaseline is the committed list of every plan-shape finding the record has today.
const shapesBaseline = "shapes"

const shapesHeader = `# Plan-shape findings the record has today, one per line:
#   <view NAME | stmt ID> | <kind> | <name> | x<plan nodes showing it>
# A stmt ID is the head of the SHA-256 of the statement's whitespace-normalised SQL; plans.golden
# prints the SQL under it. GENERATED by UPDATE_GOLDENS=1 go test ./internal/record/planguard —
# never edited by hand. TestPlanShapesMatchTheBaseline fails on a finding not listed here and on a
# line here that no longer occurs, so a fix removes its line and nothing adds one unread.
`

// target is one planned statement: a view planned on its own, or a statement the sweep issued.
type target struct {
	label, sql string
	plan       planguard.Plan
}

// THE RECORD'S PLANS CHANGE ONLY WHEN SOMEONE READS THE CHANGE.
//
// Every view the schema declares is planned on its own, and every statement the read sweep issues
// is planned as it runs. Each plan is written to plans.golden, so any change to any plan is a
// diff; each plan's shape findings are compared with the committed baseline, so a new
// automatic index, per-row scan, per-row sort or repeated subplan fails here by name, and a fixed
// one fails until its line is removed.
//
// The plans can be checked on a one-mint fixture because the record never runs ANALYZE: SQLite
// chooses them from the schema and its default estimates, which do not change with the row count
// (Recorder.shouldExplain says what would break that).
func TestPlanShapesMatchTheBaseline(t *testing.T) {
	rec, path := seedAndSweep(t)
	// AN UNMEASURED BOARD AND A CLEAN ONE ARE THE SAME EMPTY BASELINE. Checked before anything is
	// compared, so a sweep that stopped reaching the guarded driver fails here.
	if n := rec.Statements(); n < statementFloor {
		t.Fatalf("the guard saw %d statements, below the floor of %d — the sweep no longer reaches "+
			"the read paths, and a baseline compared against it would compare nothing", n, statementFloor)
	}
	if errs := rec.PlanErrors(); len(errs) > 0 {
		t.Fatalf("%d statement(s) could not be planned, so their findings are unknown:\n%s",
			len(errs), strings.Join(errs, "\n"))
	}

	db, err := sql.Open("sqlite", "file:"+filepath.ToSlash(path)+"?mode=ro")
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	ctx := context.Background()
	views, err := planguard.Views(ctx, db)
	if err != nil {
		t.Fatal(err)
	}
	an, err := planguard.NewAnalyzer(views)
	if err != nil {
		t.Fatal(err)
	}

	var targets []target
	for _, v := range views {
		q := planguard.ViewQuery(v.Name)
		p, err := planguard.PlanQuery(ctx, db, q)
		if err != nil {
			t.Fatal(err)
		}
		targets = append(targets, target{label: "view " + v.Name, sql: q, plan: p})
	}
	byID := map[string]target{}
	for _, sp := range rec.Plans() {
		norm := strings.Join(strings.Fields(sp.SQL), " ")
		sum := sha256.Sum256([]byte(norm))
		id := hex.EncodeToString(sum[:])[:12]
		byID[id] = target{label: "stmt " + id, sql: norm, plan: sp.Plan}
	}
	if len(byID) == 0 {
		t.Fatal("the sweep recorded no statement plans — nothing intercepted was planned")
	}
	ids := make([]string, 0, len(byID))
	for id := range byID {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return byID[ids[i]].sql < byID[ids[j]].sql })
	for _, id := range ids {
		targets = append(targets, byID[id])
	}

	var golden strings.Builder
	golden.WriteString("# Every view, planned on its own, then every statement the read sweep issued, with\n" +
		"# SQLite's subquery numbering removed. GENERATED by UPDATE_GOLDENS=1; read the diff.\n")
	var found []string
	for _, tg := range targets {
		golden.WriteString("\n== " + tg.label + "\n")
		if strings.HasPrefix(tg.label, "stmt ") {
			golden.WriteString("-- " + tg.sql + "\n")
		}
		golden.WriteString(tg.plan.Render())
		for _, s := range an.Shapes(tg.sql, tg.plan) {
			found = append(found, tg.label+" | "+s.String())
		}
	}
	goldentest.Assert(t, "plans", golden.String())
	compareBaseline(t, found)
}

// compareBaseline fails on a finding the baseline does not list and on a baseline line that no
// longer occurs. Under UPDATE_GOLDENS=1 it writes the baseline instead.
func compareBaseline(t *testing.T, found []string) {
	t.Helper()
	sort.Strings(found)
	path := filepath.Join("testdata", shapesBaseline+".golden")
	if goldentest.Update {
		body := shapesHeader + strings.Join(found, "\n") + "\n"
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("no findings baseline: %v\n\nGenerate it with UPDATE_GOLDENS=1 go test ./internal/record/planguard and read it", err)
	}
	want := map[string]bool{}
	for _, line := range strings.Split(strings.ReplaceAll(string(raw), "\r\n", "\n"), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		want[line] = true
	}
	got := map[string]bool{}
	for _, f := range found {
		got[f] = true
		if !want[f] {
			t.Errorf("NEW plan-shape finding, not in testdata/%s.golden:\n  %s\n"+
				"Fix the statement or the index it needs; the plan is in testdata/plans.golden.", shapesBaseline, f)
		}
	}
	var gone []string
	for w := range want {
		if !got[w] {
			gone = append(gone, w)
		}
	}
	sort.Strings(gone)
	for _, w := range gone {
		t.Errorf("baseline finding NO LONGER OCCURS:\n  %s\n"+
			"Regenerate with UPDATE_GOLDENS=1 go test ./internal/record/planguard so the baseline shrinks with the fix.", w)
	}
}
