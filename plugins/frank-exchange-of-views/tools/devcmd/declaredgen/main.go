// Command declaredgen writes the record's declared table, column and view set into the binary.
//
// Every open of a database the binary did not create holds it to the binary's own schema
// (recordsql.requireDeclaredSchema): each declared table, each of its columns, each view and the
// text SQLite stores for it. That declared side is a function of the DDL alone, so it is derived
// HERE, once per build — recordsql.DeriveDeclared applies the schema and ViewsDDL to a scratch
// in-memory database and reads back what SQLite holds — and written to
// internal/record/recordsql/declared_gen.go. `-check` fails when the committed file is not what
// the DDL derives: stale after an edit to the proto, the envelope DDL or a view, or edited by hand.
//
// It lives in this module and not under scripts/ because it reads internal/record/recordsql,
// which nothing outside the module can import. The generated file is the package's only
// declaration of the set, so a missing file is a compile error rather than an empty set the open
// would compare nothing against; restore it from git and re-run.
//
// Run from the tools module:
//
//	go run ./devcmd/declaredgen          write declared_gen.go
//	go run ./devcmd/declaredgen -check   exit 1 when the committed file is stale
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/ctoforaday/special-circumstances/plugins/frank-exchange-of-views/tools/internal/record/recordsql"
	"github.com/ctoforaday/special-circumstances/plugins/frank-exchange-of-views/tools/internal/repotree"
)

const outRel = "tools/internal/record/recordsql/declared_gen.go"

func main() {
	check := flag.Bool("check", false, "verify the committed declared set matches what the DDL derives, instead of writing it")
	flag.Parse()

	path, err := repotree.Plugin(strings.Split(outRel, "/")...)
	if err != nil {
		fail(err)
	}
	d, err := recordsql.DeriveDeclared()
	if err != nil {
		fail(fmt.Errorf("deriving the declared set: %w", err))
	}
	want, err := render(d)
	if err != nil {
		fail(err)
	}
	if !*check {
		if err := os.WriteFile(path, want, 0o644); err != nil {
			fail(err)
		}
		fmt.Printf("declaredgen: wrote %s (%d tables, %d views)\n", path, len(d.Tables), len(d.Views))
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		fail(fmt.Errorf("%s is unreadable (%v) — run `go -C plugins/frank-exchange-of-views/tools run ./devcmd/declaredgen`", path, err))
	}
	if !bytes.Equal(got, want) {
		fmt.Fprintf(os.Stderr, "declaredgen: %s is stale.\n"+
			"It is written from the record's DDL (recordsql.Schema and ViewsDDL), never by hand; the open\n"+
			"holds every older record to it, so a stale copy refuses a current record or admits a stale one.\n"+
			"Regenerate: go -C plugins/frank-exchange-of-views/tools run ./devcmd/declaredgen\n", path)
		os.Exit(1)
	}
	fmt.Printf("declaredgen: the declared set matches the DDL (%d tables, %d views)\n", len(d.Tables), len(d.Views))
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "declaredgen:", err)
	os.Exit(1)
}

// render writes the set as one Go literal, tables and views in name order and each table's columns
// sorted, so the file is byte-stable across runs.
func render(d recordsql.Declared) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by devcmd/declaredgen from the record's DDL. DO NOT EDIT.\n\n")
	b.WriteString("package recordsql\n\n")
	b.WriteString("// declared is this binary's table, column and view set, derived from Schema and ViewsDDL at build\n")
	b.WriteString("// time. See Declared.\n")
	b.WriteString("var declared = Declared{\n\tTables: []string{\n")
	for _, t := range d.Tables {
		fmt.Fprintf(&b, "\t\t%s,\n", strconv.Quote(t))
	}
	b.WriteString("\t},\n\tColumns: map[string][]string{\n")
	for _, t := range d.Tables {
		fmt.Fprintf(&b, "\t\t%s: {", strconv.Quote(t))
		for i, c := range d.Columns[t] {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(strconv.Quote(c))
		}
		b.WriteString("},\n")
	}
	b.WriteString("\t},\n\tViews: map[string]string{\n")
	names := make([]string, 0, len(d.Views))
	for v := range d.Views {
		names = append(names, v)
	}
	sort.Strings(names)
	for _, v := range names {
		fmt.Fprintf(&b, "\t\t%s: %s,\n", strconv.Quote(v), literal(d.Views[v]))
	}
	b.WriteString("\t},\n}\n")
	return format.Source(b.Bytes())
}

// literal is a raw string where the text allows one — a view definition reads as SQL in review —
// and a quoted one otherwise.
func literal(s string) string {
	if strings.ContainsAny(s, "`\r") {
		return strconv.Quote(s)
	}
	return "`" + s + "`"
}
