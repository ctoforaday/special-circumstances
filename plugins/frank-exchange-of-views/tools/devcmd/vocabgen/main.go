// Command vocabgen writes the vocabulary the record package reads at initialisation as Go literals:
// every record.proto enum value's annotations (internal/record/recordpb/annotations_gen.go) and the
// terms registry's definitions (internal/terms/definitions_gen.go). `-check` fails when a committed
// file is not what the schema and the registry render — stale after an edit to record.proto or
// terms.json, or edited by hand.
//
// It lives in this module and not under scripts/ because it reads internal/record/recordpb and
// internal/terms, which nothing outside the module can import.
//
// Run from the tools module:
//
//	go run ./devcmd/vocabgen          write the files
//	go run ./devcmd/vocabgen -check   exit 1 when a committed file is stale
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"

	"google.golang.org/protobuf/reflect/protoreflect"

	"github.com/ctoforaday/special-circumstances/plugins/frank-exchange-of-views/tools/internal/record/recordpb"
	"github.com/ctoforaday/special-circumstances/plugins/frank-exchange-of-views/tools/internal/repotree"
	"github.com/ctoforaday/special-circumstances/plugins/frank-exchange-of-views/tools/internal/terms"
)

const header = "// Code generated by `go -C plugins/frank-exchange-of-views/tools run ./devcmd/vocabgen`. DO NOT EDIT.\n\n"

// output is one generated file: where it goes, what it is written from, and its text.
type output struct {
	rel    []string
	from   string
	render func() ([]byte, error)
}

var outputs = []output{
	{[]string{"tools", "internal", "record", "recordpb", "annotations_gen.go"},
		"record.proto's enum value options. Edit the schema", renderAnnotations},
	{[]string{"tools", "internal", "terms", "definitions_gen.go"},
		"internal/terms/terms.json. Edit the registry", renderDefinitions},
}

func main() {
	check := flag.Bool("check", false, "verify each committed file matches what the schema and the registry render, instead of writing it")
	flag.Parse()

	stale := false
	for _, o := range outputs {
		path, err := repotree.Plugin(o.rel...)
		if err != nil {
			fail(err)
		}
		want, err := o.render()
		if err != nil {
			fail(err)
		}
		cur, err := os.ReadFile(path)
		if err != nil && !os.IsNotExist(err) {
			fail(err)
		}
		if bytes.Equal(cur, want) {
			continue
		}
		stale = true
		if *check {
			fmt.Fprintf(os.Stderr, "vocabgen: %s is stale.\nIt is written from %s, never the file.\n", path, o.from)
			continue
		}
		if err := os.WriteFile(path, want, 0o644); err != nil {
			fail(err)
		}
		fmt.Printf("vocabgen: wrote %s\n", path)
	}
	if !stale {
		fmt.Println("vocabgen: the generated vocabulary matches the schema and the registry")
		return
	}
	if *check {
		fmt.Fprintln(os.Stderr, "Regenerate: go -C plugins/frank-exchange-of-views/tools run ./devcmd/vocabgen")
		os.Exit(1)
	}
}

// renderAnnotations writes one array per enum, indexed as the enum's values are, and the switch
// that finds it by the enum's full name: a literal array is laid out by the linker, so reading a
// row allocates nothing and initialises nothing.
func renderAnnotations() ([]byte, error) {
	enums := recordEnums(recordpb.File_record_proto.Enums(), recordpb.File_record_proto.Messages(), nil)
	if len(enums) == 0 {
		return nil, fmt.Errorf("record.proto declares no enums — a table of nothing would read every value as unannotated")
	}
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package recordpb\n\nimport \"google.golang.org/protobuf/reflect/protoreflect\"\n\n")
	b.WriteString("// generatedAnnotations is the annotation table for one record.proto enum, in the enum's value order.\n")
	b.WriteString("func generatedAnnotations(enum protoreflect.FullName) []ValueAnnotations {\n\tswitch enum {\n")
	for _, ed := range enums {
		fmt.Fprintf(&b, "\tcase %q:\n\t\treturn %s[:]\n", ed.FullName(), varName(ed))
	}
	b.WriteString("\t}\n\treturn nil\n}\n")
	for _, ed := range enums {
		fmt.Fprintf(&b, "\nvar %s = [...]ValueAnnotations{\n", varName(ed))
		for i := 0; i < ed.Values().Len(); i++ {
			b.WriteString("\t" + annotationLiteral(recordpb.AnnotationsFromOptions(ed.Values().Get(i))) + ",\n")
		}
		b.WriteString("}\n")
	}
	return format.Source(b.Bytes())
}

// recordEnums is every enum the file declares, top-level and nested, in declaration order.
func recordEnums(es protoreflect.EnumDescriptors, ms protoreflect.MessageDescriptors, out []protoreflect.EnumDescriptor) []protoreflect.EnumDescriptor {
	for i := 0; i < es.Len(); i++ {
		out = append(out, es.Get(i))
	}
	for i := 0; i < ms.Len(); i++ {
		out = recordEnums(ms.Get(i).Enums(), ms.Get(i).Messages(), out)
	}
	return out
}

func varName(ed protoreflect.EnumDescriptor) string {
	pkg := string(ed.ParentFile().Package())
	name := strings.TrimPrefix(string(ed.FullName()), pkg+".")
	return "annotations" + strings.ReplaceAll(name, ".", "_")
}

// annotationLiteral states only the fields a value declares, so a row reads as its annotations.
func annotationLiteral(a recordpb.ValueAnnotations) string {
	fields := []string{"Name: " + strconv.Quote(string(a.Name))}
	str := func(name, v string) {
		if v != "" {
			fields = append(fields, name+": "+strconv.Quote(v))
		}
	}
	flag := func(name string, d recordpb.DeclaredBool) {
		if d.Declared {
			fields = append(fields, fmt.Sprintf("%s: DeclaredBool{Declared: true, Value: %t}", name, d.Value))
		}
	}
	str("Means", a.Means)
	str("DefinedTerm", a.DefinedTerm)
	str("RuledBy", a.RuledBy)
	str("Neighbor", a.Neighbor)
	str("Distinguisher", a.Distinguisher)
	flag("Closes", a.Closes)
	flag("SeatMayFile", a.SeatMayFile)
	if a.Mass.Declared {
		fields = append(fields, "Mass: DeclaredNumber{Declared: true, Value: "+strconv.FormatFloat(a.Mass.Value, 'g', -1, 64)+"}")
	}
	if a.MaterialDefault.Declared {
		fields = append(fields, fmt.Sprintf("MaterialDefault: DeclaredEnum{Declared: true, Value: %d}", a.MaterialDefault.Value))
	}
	flag("FindsAgainst", a.FindsAgainst)
	return "{" + strings.Join(fields, ", ") + "}"
}

// renderDefinitions writes the registry's terms, definitions and seats, from a registry that loads:
// a registry the vocabulary gate would refuse is never written into a table every process reads.
func renderDefinitions() ([]byte, error) {
	reg, err := terms.Load()
	if err != nil {
		return nil, fmt.Errorf("the terms registry does not load: %w", err)
	}
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package terms\n\n// definitions is the registry's entries, in registry order.\nvar definitions = [...]Definition{\n")
	for _, e := range reg.Entries {
		d := terms.DefinitionOf(e)
		seats := make([]string, len(d.Seats))
		for i, s := range d.Seats {
			seats[i] = strconv.Quote(s)
		}
		fmt.Fprintf(&b, "\t{Term: %s, Definition: %s, Seats: []string{%s}},\n",
			strconv.Quote(d.Term), strconv.Quote(d.Definition), strings.Join(seats, ", "))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "vocabgen:", err)
	os.Exit(1)
}
