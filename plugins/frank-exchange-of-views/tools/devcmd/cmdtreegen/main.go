// Command cmdtreegen writes the command tree's fixed tables: every verb's rendered help page, and
// every event body's required fields.
//
// Every feov-record process builds its whole command tree, and both tables were computed per
// process from inputs that are fixed at build time. The help pages are templates over values from
// fixed tables (seat.HelpValues); the required fields are the `(sql).required` annotations on the
// record's schema. Computing them per process was half of the tree's build. This writes each
// answer once:
//
//	internal/cli/seat/help_gen.go       seat.RenderHelp for every help/*.md document
//	internal/record/required_gen.go     record.RequiredFieldsFromSchema for every event body
//
// `-check` fails when either committed file is not what its source renders — stale after an edit
// to a help document, a HelpValues table or the schema's annotations, or edited by hand.
//
// It lives in this module and not under scripts/ because the render needs internal/cli's package
// inits — they supply seat.HelpValues — and the derivation is internal/record's, neither of which
// anything outside the module can import. It is not protogen because protogen compiles the
// schema in the scripts module and cannot call the record's own derivation; generating from that
// derivation keeps one statement of what "required" means.
//
// Run from the tools module:
//
//	go run ./devcmd/cmdtreegen          write the tables
//	go run ./devcmd/cmdtreegen -check   exit 1 when a committed table is stale
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"

	"google.golang.org/protobuf/reflect/protoreflect"

	// THE INITS ARE THE POINT. Package cli links every role's verbs, and their inits supply the
	// values the help documents render.
	_ "github.com/ctoforaday/special-circumstances/plugins/frank-exchange-of-views/tools/internal/cli"
	"github.com/ctoforaday/special-circumstances/plugins/frank-exchange-of-views/tools/internal/cli/seat"
	"github.com/ctoforaday/special-circumstances/plugins/frank-exchange-of-views/tools/internal/record"
	"github.com/ctoforaday/special-circumstances/plugins/frank-exchange-of-views/tools/internal/record/recordpb"
	"github.com/ctoforaday/special-circumstances/plugins/frank-exchange-of-views/tools/internal/repotree"
)

const header = "// Code generated by go -C plugins/frank-exchange-of-views/tools run ./devcmd/cmdtreegen. DO NOT EDIT.\n\n"

type table struct {
	rel    string // under the plugin directory
	from   string
	render func() ([]byte, error)
}

var tables = []table{
	{"tools/internal/cli/seat/help_gen.go", "internal/cli/seat/help/*.md and seat.HelpValues", renderHelp},
	{"tools/internal/record/required_gen.go", "the (sql).required annotations in record.proto", renderRequired},
}

func main() {
	check := flag.Bool("check", false, "verify each committed table matches what its source renders, instead of writing it")
	flag.Parse()

	stale := false
	for _, t := range tables {
		path, err := repotree.Plugin(t.rel)
		if err != nil {
			fail(err)
		}
		want, err := t.render()
		if err != nil {
			fail(fmt.Errorf("%s: %w", t.rel, err))
		}
		cur, err := os.ReadFile(path)
		if err != nil && !os.IsNotExist(err) {
			fail(err)
		}
		if bytes.Equal(cur, want) {
			continue
		}
		stale = true
		if *check {
			fmt.Fprintf(os.Stderr, "cmdtreegen: %s is stale.\nIt is written from %s, never by hand.\n", path, t.from)
			continue
		}
		if err := os.WriteFile(path, want, 0o644); err != nil {
			fail(err)
		}
		fmt.Printf("cmdtreegen: wrote %s\n", path)
	}
	if !stale {
		fmt.Println("cmdtreegen: the command tree's generated tables match their sources")
		return
	}
	if *check {
		fmt.Fprintln(os.Stderr, "Regenerate: go -C plugins/frank-exchange-of-views/tools run ./devcmd/cmdtreegen")
		os.Exit(1)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "cmdtreegen:", err)
	os.Exit(1)
}

// renderHelp is every document's page, refused whole when one does not render: a page missing
// from the table is a verb that panics at construction.
func renderHelp() ([]byte, error) {
	names := seat.HelpNames()
	if len(names) == 0 {
		return nil, fmt.Errorf("no help documents embedded")
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("package seat\n\n")
	b.WriteString("// generatedHelp is each help document's page as RenderHelp renders it. See help.go.\n")
	b.WriteString("func generatedHelp(key string) (helpDoc, bool) {\n\tswitch key {\n")
	for _, n := range names {
		menu, detail, err := seat.RenderHelp(n)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\tcase %s:\n\t\treturn helpDoc{\n\t\t\tmenu:   %s,\n\t\t\tdetail: %s,\n\t\t}, true\n",
			strconv.Quote(n), strconv.Quote(menu), strconv.Quote(detail))
	}
	b.WriteString("\t}\n\treturn helpDoc{}, false\n}\n")
	return format.Source([]byte(b.String()))
}

// renderRequired is each event body's required fields, one package-level slice per body that has
// any, so a lookup allocates nothing.
func renderRequired() ([]byte, error) {
	od := (&recordpb.Event{}).ProtoReflect().Descriptor().Oneofs().ByName("body")
	if od == nil {
		return nil, fmt.Errorf("the Event message has no body oneof")
	}
	type body struct {
		name   string
		fields []record.RequiredField
	}
	var bodies []body
	for i := 0; i < od.Fields().Len(); i++ {
		fd := od.Fields().Get(i)
		if fd.Kind() != protoreflect.MessageKind {
			continue
		}
		if rf := record.RequiredFieldsFromSchema(string(fd.Name())); len(rf) > 0 {
			bodies = append(bodies, body{string(fd.Name()), rf})
		}
	}
	if len(bodies) == 0 {
		return nil, fmt.Errorf("no event body requires a field — the schema's annotations did not read")
	}
	sort.Slice(bodies, func(i, j int) bool { return bodies[i].name < bodies[j].name })
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("package record\n\n")
	b.WriteString("// requiredFieldsOf is RequiredFieldsFromSchema for each event body. See required.go.\n")
	b.WriteString("func requiredFieldsOf(typ string) []RequiredField {\n\tswitch typ {\n")
	for _, bd := range bodies {
		fmt.Fprintf(&b, "\tcase %s:\n\t\treturn %s\n", strconv.Quote(bd.name), varName(bd.name))
	}
	b.WriteString("\t}\n\treturn nil\n}\n\nvar (\n")
	for _, bd := range bodies {
		fmt.Fprintf(&b, "\t%s = []RequiredField{\n", varName(bd.name))
		for _, f := range bd.fields {
			fmt.Fprintf(&b, "\t\t{Key: %s, Flag: %s", strconv.Quote(f.Key), strconv.Quote(f.Flag))
			if f.Arm != "" {
				fmt.Fprintf(&b, ", Arm: %s", strconv.Quote(f.Arm))
			}
			b.WriteString("},\n")
		}
		b.WriteString("\t}\n")
	}
	b.WriteString(")\n")
	return format.Source([]byte(b.String()))
}

// varName is a body's slice: `motion_rule` → requiredMotionRule.
func varName(body string) string {
	var b strings.Builder
	b.WriteString("required")
	for _, w := range strings.Split(body, "_") {
		if w != "" {
			b.WriteString(strings.ToUpper(w[:1]) + w[1:])
		}
	}
	return b.String()
}
